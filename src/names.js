export function givenName(rng, culture, sex) {
  const c = CULTURES[culture];
  return rng.pick(sex === 'M' ? c.male : c.female);
}

export function dynastyName(rng, culture, used) {
  const c = CULTURES[culture];
  for (let tries = 0; tries < 50; tries++) {
    let n = rng.pick(c.syl) + rng.pick(c.syl);
    if (rng.chance(0.3)) n += rng.pick(c.syl);
    n = n.replace(/^[ンッェー]/, 'ア') + rng.pick(c.suffix);
    if (!used.has(n)) {
      used.add(n);
      return n;
    }
  }
  return `${rng.pick(c.syl)}${used.size}${rng.pick(c.suffix)}`;
}

export function kingdomName(rng, culture, used) {
  const c = CULTURES[culture];
  const free = c.kingdoms.filter((k) => !used.has(k));
  const base = free.length ? rng.pick(free) : `新${rng.pick(c.kingdoms)}`;
  used.add(base);
  return base;
}

const PROV_SYL = ['ア', 'ベ', 'カ', 'ド', 'エ', 'フ', 'ガ', 'ヘ', 'イ', 'ケ', 'ラ', 'マ', 'ノ', 'オ', 'パ', 'リ', 'サ', 'ト', 'ウ', 'ヴ', 'ロ', 'シ', 'ザ', 'ミ'];
const PROV_SUF = ['ブルク', 'ポリス', 'ベルク', 'ムント', 'フォルト', 'ハーフェン', 'ヴァル', 'リア', 'ンタ', 'ドール'];
export function provinceName(rng, used) {
  for (let tries = 0; tries < 50; tries++) {
    const n = rng.pick(PROV_SYL) + rng.pick(PROV_SYL) + rng.pick(PROV_SUF);
    if (!used.has(n)) {
      used.add(n);
      return n;
    }
  }
  return `地方${used.size}`;
}

// ローマ数字ではなく漢数字の「〇世」
export function regnalSuffix(n) {
  return n >= 2 ? `${n}世` : '';
}
